import type { Discovery, InterestId } from '@/src/domain/types';

const demo = (id: string, title: string): Discovery['sources'][number] => ({
  id,
  title,
  note: 'DEMO / UNVERIFIED — illustrative sample copy only. Not a published citation.',
});

type Spec = {
  id: string;
  slug: string;
  title: string;
  hook: string;
  brief: string;
  why: string;
  dive: string;
  quality: number;
  interests: [InterestId, number][];
  accent: string;
  motif: string;
};

function card(s: Spec): Discovery {
  return {
    id: s.id,
    slug: s.slug,
    title: s.title,
    hook: s.hook,
    brief: s.brief,
    whyItMatters: s.why,
    deepDive: `DEMO ONLY. ${s.dive}`,
    qualityScore: s.quality,
    interests: s.interests.map(([interestId, weight]) => ({ interestId, weight })),
    sources: [demo(`s-${s.id}`, `Demo: ${s.slug}`)],
    accentColor: s.accent,
    visualMotif: s.motif,
    isDemo: true,
  };
}

